const VIBE_KEYWORDS: Array<{ id: string; pattern: RegExp }> = [
  { id: 'chill', pattern: /\b(chill|calm|peaceful|serene|ocean|blue|soft)\b/i },
  { id: 'bold', pattern: /\b(bold|vibrant|energetic|fire|hot|dynamic)\b/i },
  { id: 'pastel', pattern: /\b(pastel|dreamy|soft|pink|lavender|aesthetic)\b/i },
  { id: 'neon', pattern: /\b(neon|cyber|electric|glow|synth)\b/i },
  { id: 'nature', pattern: /\b(nature|forest|earth|green|organic)\b/i },
  { id: 'minimal', pattern: /\b(minimal|clean|monochrome|simple|modern)\b/i },
  { id: 'cozy', pattern: /\b(cozy|warm|amber|autumn|coffee)\b/i },
  { id: 'dark', pattern: /\b(dark|mysterious|gothic|midnight|purple|violet)\b/i },
];

export function detectVibeFromPrompt(prompt: string): string | null {
  const text = prompt.toLowerCase();
  for (const { id, pattern } of VIBE_KEYWORDS) {
    if (pattern.test(text)) return id;
  }
  return null;
}

export function buildLocalVibeTheme(vibeId: string | null | undefined): GeneratedTheme {
  const key = vibeId && LOCAL_VIBE_THEMES[vibeId] ? vibeId : 'dark';
  return { ...LOCAL_VIBE_THEMES[key] };
}

export function isValidGeneratedTheme(t: unknown): t is GeneratedTheme {
  if (!t || typeof t !== 'object') return false;
  const o = t as Record<string, unknown>;
  const primary =
    o.colorPrimary ?? o.primary ?? o['--primary'] ?? (o.tokens as Record<string, unknown> | undefined)?.colorPrimary;
  return typeof primary === 'string' && primary.length > 0;
}
